// Where the app finds the backend. The defaults point at the host machine from an emulator
// (10.0.2.2 is the emulator's alias for the host). Override with -PapiBaseUrl=... or the
// PLM_API_BASE_URL environment variable, and likewise for the tile server.
fun urlSetting(property: String, env: String, default: String): String =
    providers.gradleProperty(property)
        .orElse(providers.environmentVariable(env))
        .orElse(default)
        .get()
        .trimEnd('/')

